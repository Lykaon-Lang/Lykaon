/// Base types (G107).
pub const BASE_TYPES: &[&str] = &[
    "whole number", "decimal", "exact decimal", "big number", "text", "yes or no",
    "letter", "bytes",
];

/// Binary operators (G72).
pub const BINOPS: &[&str] = &[
    "plus", "minus", "times", "divided by", "whole divided by", "to the power of",
];

/// Postfix words that trigger the ambiguity rule T0130.
pub const POSTFIX: &[&str] = &[
    "sorted", "sorted descending", "reversed", "unique", "trimmed", "backwards",
    "rounded", "rounded to even", "fallback", "joined with", "normalized",
    "shuffled", "as",
];

/// The common diagnostic codes and their plain-English meaning.
pub const ERROR_CODES: &[(&str, &str)] = &[
    ("T0101", "A word with a fixed meaning is used in a name."),
    ("T0109", "Two postfix words appear in a row."),
    ("T0110", "The sentence does not start with an action word."),
    ("T0113", "The sentence cannot be read."),
    ("T0130", "A postfix word makes the sentence ambiguous."),
    ("T0205", "A name is not defined."),
    ("T0301", "A value of one kind is used where another is needed."),
    ("T0302", "A whole number and a decimal meet in one operation."),
    ("T0330", "A shared/recursive function must state its input kinds."),
    ("T0331", "A recursive function must state its result kind."),
    ("T0401", "A value is used after it was given away."),
    ("T0406", "A fixed name was changed."),
    ("T0509", "A sentence belongs to a later milestone."),
    ("T0611", "The memory limit was reached."),
    ("T0612", "The time limit was reached."),
    ("T0622", "The sandbox refused an action."),
];

/// The EBNF export.
pub fn export_ebnf() -> String {
    let mut s = String::new();
    s.push_str("% Lykaon M1-M4 grammar (implemented)\n");
    s.push_str("% Generated by `lykaon grammar --export`.\n\n");
    s.push_str("program        = { top_item } .\n");
    s.push_str("top_item       = note | about | function | record | enum | interface\n");
    s.push_str("               | impl | use_stmt | share_stmt | const_def | test_block\n");
    s.push_str("               | statement .\n");
    s.push_str("statement      = simple_stmt | block_stmt .\n");
    s.push_str("block          = INDENT { statement } DEDENT .\n\n");
    s.push_str("(* declarations *) \n");
    s.push_str("define         = NAME \"is\" expr \".\" .\n");
    s.push_str("changeable     = \"Changeable\" NAME \"is\" expr \".\" .\n");
    s.push_str("const_def      = \"Constant\" NAME \"is\" literal \".\" .\n");
    s.push_str("set            = \"Set\" place \"to\" expr \".\" .\n\n");
    s.push_str("(* output and input *) \n");
    s.push_str("say            = \"Say\" expr [ fmt ] \".\" .\n");
    s.push_str("say_lines      = \"Say\" \"lines\" \".\" INDENT { TEXT_LINE } DEDENT .\n");
    s.push_str("ask            = \"Ask\" NAME [ \"as\" type ] \".\" .\n");
    s.push_str("fmt            = \"to\" NUMBER \"places\" | \"width\" NUMBER .\n\n");
    s.push_str("(* control *) \n");
    s.push_str("if_block       = \"If\" cond \".\" block .\n");
    s.push_str("otherwise      = \"Otherwise\" [ \"if\" cond ] \".\" block .\n");
    s.push_str("repeat_block   = \"Repeat\" ( NUMBER \"times\" | \"while\" cond | \"forever\" ) \".\" block .\n");
    s.push_str("for_each_in    = \"For\" \"each\" names \"in\" expr \".\" block .\n");
    s.push_str("for_each_range = \"For\" \"each\" NAME \"from\" expr \"to\" expr \".\" block .\n");
    s.push_str("try_block      = \"Try\" [ failing_stmt ] \".\" block\n");
    s.push_str("                 \"If\" \"that\" \"fails\" [ \"with\" kind ] \".\" block .\n");
    s.push_str("look_block     = \"Look\" \"at\" operand \".\" { when_block } .\n");
    s.push_str("when_block     = \"When\" variant_name { NAME } \".\" block .\n\n");
    s.push_str("(* functions *) \n");
    s.push_str("function       = \"To\" name [ param ] { \"with\" param } [ \"can\" \"fail\" ]\n");
    s.push_str("                 ( \"give\" expr \".\" | \".\" block ) .\n");
    s.push_str("param          = [ \"give\" | \"lend\" \"to\" \"change\" ] NAME\n");
    s.push_str("                 [ \"as\" type ] [ \"defaulting\" \"to\" operand ] .\n");
    s.push_str("give_back      = \"Give\" \"back\" expr [ \"as\" type ] \".\" .\n");
    s.push_str("hand_back      = \"Hand\" \"back\" expr \".\" .\n\n");
    s.push_str("(* data *) \n");
    s.push_str("record         = \"A\" NAME \"has\" field { \"and\" field } \".\" [ block ] .\n");
    s.push_str("field          = NAME \"as\" type .\n");
    s.push_str("enum           = \"A\" NAME \"is\" variant { \"or\" variant } \".\" .\n");
    s.push_str("variant        = NAME [ \"with\" field ] .\n\n");
    s.push_str("(* types *) \n");
    s.push_str("type           = base_type | \"list\" \"of\" type | \"map\" \"of\" type \"to\" type\n");
    s.push_str("               | \"set\" \"of\" type | \"queue\" \"of\" type | \"maybe\" type\n");
    s.push_str("               | \"pair\" \"of\" type \"and\" type | \"array\" \"of\" NUMBER type | NAME .\n");
    s.push_str(&format!("base_type      = {} .\n\n", quote_join(BASE_TYPES)));
    s.push_str("(* expressions *) \n");
    s.push_str("expr           = operand | operand BINOP operand | call | postfix .\n");
    s.push_str(&format!("BINOP          = {} .\n", quote_join(BINOPS)));
    s.push_str(&format!("postfix        = {} .\n", quote_join(POSTFIX)));
    s.push_str("call           = name [ operand ] { \"with\" operand } .\n");
    s.push_str("cond           = comparison { ( \"and\" | \"or\" ) comparison } | \"not\" cond .\n");
    s.push_str("comparison     = operand cmp operand | operand \"is\" \"missing\" .\n");
    s.push_str("cmp            = \"is\" | \"is not\" | \"is more than\" | \"is less than\"\n");
    s.push_str("               | \"is at least\" | \"is at most\" | \"is between\" operand \"and\" .\n");
    s
}

fn quote_join(xs: &[&str]) -> String {
    xs.iter()
        .map(|x| format!("\"{x}\""))
        .collect::<Vec<_>>()
        .join(" | ")
}

/// The JSON export.
pub fn export_json() -> String {
    let v = serde_json::json!({
        "language": "Lykaon",
        "milestones": "M1-M4",
        "sentence_end": ".",
        "block": "INDENT { statement } DEDENT",
        "comments": ["Note ...", "About ..."],
        "statement_starters": STARTERS,
        "base_types": BASE_TYPES,
        "binops": BINOPS,
        "postfix": POSTFIX,
        "error_codes": ERROR_CODES.iter().map(|(c, m)| serde_json::json!({"code": c, "meaning": m})).collect::<Vec<_>>(),
    });
    serde_json::to_string_pretty(&v).unwrap_or_else(|_| "{}".to_string())
}