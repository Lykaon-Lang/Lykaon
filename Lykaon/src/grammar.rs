//! M5c item 4: `lykaon grammar --export`.
//!
//! Emits the implemented M1-M4 grammar as EBNF (default) or JSON (`--json`).
//! The rule set mirrors the language the compiler accepts; it is kept in one
//! place so tooling (editors, docs, AI) can read it. This is the language
//! definition, not a parser dump.

